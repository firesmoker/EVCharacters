import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
const { chromium } = await import(process.env.EV_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage();
  await page.goto('http://127.0.0.1:5174/');
  const path = new URL('../src/templates/bard_liora_vey_full_build.json', import.meta.url);
  const fixture = JSON.parse(readFileSync(path, 'utf8'));
  delete fixture.portrait;
  const save = () => page.evaluate(async () => JSON.parse((await import('/src/io.js')).serializeSheet()));
  await page.evaluate(async data => (await import('/src/io.js')).loadFromJSON(JSON.stringify(data)), fixture);
  await page.evaluate(() => document.fonts.ready);
  const frame = page.locator('.portrait-frame');
  assert.equal(await frame.isVisible(), false);
  await page.locator('#portrait-enabled').check();
  assert(await frame.isVisible());
  await page.emulateMedia({ media: 'print' });
  assert(await frame.isVisible(), 'Enabled blank portrait prints');
  assert.equal(await page.locator('.portrait-placeholder').isVisible(), false);
  assert.equal(await page.locator('.portrait-toggle').isVisible(), false);
  const box = await frame.boundingBox(); assert(Math.abs(box.width - box.height) < 1);
  await page.emulateMedia({ media: 'screen' });
  await page.locator('#portrait-upload').setInputFiles(new URL('../public/liora-vey.png', import.meta.url).pathname.replace(/^\/(\w:)/, '$1'));
  await page.waitForFunction(() => document.querySelector('.portrait-frame img').src.startsWith('data:image/jpeg;'));
  const dialog = page.getByRole('dialog', { name: 'Adjust portrait crop' });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  const uploaded = (await save()).portrait;
  assert(uploaded.image.length < 500000, 'Portrait is compact enough to embed in saves');
  await page.locator('[data-sync-id="character-name"]').first().click();
  await page.keyboard.press('ControlOrMeta+z');
  assert.equal((await save()).portrait.image, '', 'Upload can be undone');
  await page.keyboard.press('ControlOrMeta+y');
  assert.deepEqual((await save()).portrait, uploaded);
  await page.getByRole('button', { name: 'Adjust crop', exact: true }).click();
  await dialog.getByLabel('Zoom', { exact: true }).fill('1.5');
  await dialog.getByLabel('Horizontal position').fill('35');
  await dialog.getByLabel('Vertical position').fill('25');
  await dialog.getByRole('button', { name: 'Apply crop' }).click();
  assert.deepEqual((await save()).portrait.crop, { zoom: 1.5, x: 35, y: 25 });
  await page.locator('[data-sync-id="character-name"]').first().click();
  await page.keyboard.press('ControlOrMeta+z');
  assert.deepEqual((await save()).portrait.crop, uploaded.crop, 'Crop can be undone');
  await page.getByRole('button', { name: 'Adjust crop', exact: true }).click();
  await dialog.getByLabel('Zoom', { exact: true }).fill('2');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.deepEqual((await save()).portrait.crop, uploaded.crop, 'Cancel preserves original crop');
  await page.locator('#portrait-enabled').uncheck();
  assert.equal(await frame.isVisible(), false);
  assert.equal((await save()).portrait.image, uploaded.image, 'Turning off retains portrait');
  await page.emulateMedia({ media: 'print' });
  assert.equal(await frame.isVisible(), false, 'Disabled portrait does not print');
  await page.emulateMedia({ media: 'screen' });
  await page.locator('#portrait-enabled').check();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('ev-char-sheet') || '{}').portrait?.enabled);
  await page.reload(); await page.evaluate(() => document.fonts.ready);
  assert.deepEqual((await save()).portrait, uploaded, 'Portrait survives reload');
  assert.equal(await page.locator('.portrait-frame').count(), 1, 'Only first page has a portrait');
  const centers = await page.evaluate(() => {
    const page = document.querySelector('.character-page');
    const center = el => { const r = el.getBoundingClientRect(); return r.x + r.width / 2; };
    return [center(page), center(page.querySelector('.sheet-title')), center(page.querySelector('.sheet-wordmark'))];
  });
  assert(centers.every(c => Math.abs(c - centers[0]) < 1), 'Name and wordmark remain centered on the page');
  assert(await page.evaluate(() => [...document.querySelectorAll('.a4-page')].every(p => p.scrollHeight <= p.clientHeight + 2)), 'A4 pages do not overflow');
  if (process.env.EV_SAVE_LIORA_PORTRAIT) {
    fixture.portrait = uploaded;
    writeFileSync(path, JSON.stringify(fixture, null, 2) + '\n');
  }
  console.log('Portrait upload, blank/hidden print states, undo/redo, persistence and A4 layout passed.');
} finally { await browser.close(); }
