import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { chromium } = await import(process.env.EV_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage();
  page.on('pageerror', error => console.error(error));
  await page.goto('http://127.0.0.1:5174/');
  const data = JSON.parse(readFileSync(new URL('../src/templates/bard_liora_vey_full_build.json', import.meta.url)));
  const result = await page.evaluate(async data => {
    const io = await import('/src/io.js');
    const format = await import('/src/section-format.js');
    const tools = await import('/src/sheet-tools.js');
    tools.initSheetTools();
    io.loadFromJSON(JSON.stringify(data));
    await document.fonts.ready;
    format.setSectionSize('fixed');
    tools.paginateSheets();
    const saved = io.serializeSheet();
    io.loadFromJSON(saved);
    tools.paginateSheets();
    const counts = [...document.querySelectorAll('.character-page .dynamic-rows')].map(el => el.children.length);
    const skillLayout = ['combat-skills', 'standard-skills'].map(name => {
      const box = document.querySelector(`[data-section="${name}"]`);
      const inputs = [...box.querySelectorAll('input')];
      return { fonts: inputs.map(input => parseFloat(getComputedStyle(input).fontSize)),
        rowsFit: [...box.querySelectorAll('.skill-row')].every(row => row.getBoundingClientRect().bottom <= box.getBoundingClientRect().bottom) };
    });
    const boxes = [...document.querySelectorAll('.character-page .sheet-column:last-child .section-box')];
    const heights = boxes.map(el => el.getBoundingClientRect().height);
    const overflow = boxes.flatMap(el => [el, ...el.querySelectorAll('.section-content')].map(part => part.scrollHeight - part.clientHeight));
    const mode = format.isFixedSize();
    const actions = document.querySelectorAll('.actions-page .strikes-cantrips-container').length;
    const spells = document.querySelectorAll('[data-section="spells-known"] .skill-row').length;
    const additional = document.querySelector('[data-section="additional-features"]').getBoundingClientRect().height;
    const feats = document.querySelector('[data-section="feats"]').getBoundingClientRect().height;
    const compact = ['languages', 'death', 'spellcasting'].map(name => document.querySelector(`[data-section="${name}"]`).getBoundingClientRect().height);
    document.querySelector('.exclusive-traditions .checkbox-item:last-child input').checked = true;
    const necromancy = JSON.parse(io.serializeSheet()).sections.Spellcasting.checkboxes.Necromancy;
    const notesInput = document.querySelector('.spell-notes input');
    notesInput.value = 'Once per day';
    const withNotes = io.serializeSheet();
    io.loadFromJSON(withNotes);
    const notes = document.querySelector('.spell-notes input').value;
    format.setSectionSize('auto');
    tools.paginateSheets();
    const restored = boxes.every(el => !el.style.height);
    const autoSaved = io.serializeSheet();
    io.loadFromJSON(autoSaved);
    const autoRestored = !format.isFixedSize();
    const legacy = JSON.parse(saved);
    delete legacy.preferences.sectionSize;
    io.loadFromJSON(JSON.stringify(legacy));
    const legacyDefaultsFixed = format.isFixedSize();
    io.prepareSheetForData(true);
    const combat = [...document.querySelectorAll('[data-section="combat-skills"] input[placeholder="Skill"]')].map(el => el.value);
    const standard = [...document.querySelectorAll('[data-section="standard-skills"] input')].every(el => !el.value);
    return { skillLayout, counts, heights, overflow, mode, actions, spells, additional, feats, compact, necromancy, notes, combat, standard, restored, autoRestored, legacyDefaultsFixed, saved: JSON.parse(saved) };
  }, data);
  assert.deepEqual(result.counts, [5, 11, 3]);
  assert(result.skillLayout.every(section => section.rowsFit && section.fonts.every(size => size >= 13)), JSON.stringify(result.skillLayout));
  assert(result.mode && result.restored);
  assert(result.autoRestored && result.legacyDefaultsFixed);
  assert.equal(result.saved.preferences.sectionSize, 'fixed');
  assert.equal(result.actions, 4);
  assert.equal(result.necromancy, true);
  assert.equal(result.notes, 'Once per day');
  assert.deepEqual(result.combat, ['Magic', 'Melee', 'Ranged', 'Unarmed', 'Weapon Throw']);
  assert(result.standard);
  assert(result.spells >= 25, JSON.stringify({ spells: result.spells, compact: result.compact }));
  assert.equal(result.additional, result.feats);
  assert.deepEqual(result.compact, [58, 98, 174]);
  assert(result.heights[1] > result.heights[0] * 2);
  assert(result.overflow.every(n => n <= 1), JSON.stringify(result));
  assert.equal(result.saved.sections['Class Features'].sectionBody, data.sections['Class Features'].sectionBody);
  console.log('Fixed sizes, row counts, fit, persistence, and Auto restoration passed.');
} finally { await browser.close(); }
