import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { chromium } = await import(process.env.EV_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
 const page = await browser.newPage();
 await page.goto('http://127.0.0.1:5174/');
 const fixture = JSON.parse(readFileSync(new URL('../src/templates/bard_liora_vey_full_build.json', import.meta.url), 'utf8'));
 await page.evaluate(async data => (await import('/src/io.js')).loadFromJSON(JSON.stringify(data)), fixture);
 await page.evaluate(() => document.fonts.ready);
 const save = () => page.evaluate(async () => JSON.parse((await import('/src/io.js')).serializeSheet()));
 const before = await save();
 const field = page.locator('[data-section="class-features"] .section-content').first();
 await field.click(); await field.press('ControlOrMeta+Home');
 await field.pressSequentially('UNDO TEST ');
 await page.waitForTimeout(150);
 const typed = await save();
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'Undo must restore every feature, including continuation text');
 await page.keyboard.press('ControlOrMeta+y');
 assert.deepEqual((await save()).sections, typed.sections, 'Redo restores the edit');
 await page.keyboard.press('ControlOrMeta+z');
 await page.keyboard.press('ControlOrMeta+Shift+z');
 assert.deepEqual((await save()).sections, typed.sections, 'Shift+Z also redoes');
 await page.keyboard.press('ControlOrMeta+z');
 const continuation = page.locator('[data-section="class-features"] .section-content').last();
 await continuation.click(); await continuation.press('ControlOrMeta+End');
 await continuation.pressSequentially(' NEW BRANCH');
 const branched = await save();
 await page.keyboard.press('ControlOrMeta+y');
 assert.deepEqual((await save()).sections, branched.sections, 'New edits clear redo history');
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'Undo restores continuation edits');
 const description = page.locator('[data-section="instinct-abilities"] .section-content').first();
 await description.click(); await description.press('ControlOrMeta+End');
 await description.pressSequentially(' CHECK');
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'Instinct descriptions undo');
 const checkbox = page.locator('.a4-page input[type="checkbox"]').first();
 await checkbox.click();
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'Checkbox changes undo');
 const input = page.locator('[data-section="standard-skills"] input.skill-name').first();
 await input.click(); await input.press('End'); await input.pressSequentially(' CHECK');
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'Plain inputs undo');
 const add = page.locator('[data-section="standard-skills"] .add-row-btn').last();
 await add.click({ force: true });
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'Adding a row can be undone');
 await field.click(); await field.press('ControlOrMeta+Home');
 await field.press('ControlOrMeta+Shift+8');
 assert.notDeepEqual((await save()).sections, before.sections, 'Formatting changed rich text');
 await page.keyboard.press('ControlOrMeta+z');
 assert.deepEqual((await save()).sections, before.sections, 'List formatting can be undone');
 await page.waitForFunction(expected => {
   const saved = JSON.parse(localStorage.getItem('ev-char-sheet') || '{}');
   return JSON.stringify(saved.sections) === JSON.stringify(expected);
 }, before.sections);
 await page.reload(); await page.evaluate(() => document.fonts.ready);
 assert.deepEqual((await save()).sections, before.sections, 'Undo is autosaved and survives reload');
 console.log('Undo/redo, continuation edits, rich text, inputs, checkboxes, redo branching and persistence passed.');
} finally { await browser.close(); }
